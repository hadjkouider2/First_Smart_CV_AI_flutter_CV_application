  static List<String> getCategories() {
    return ['All', 'Modern', 'Professional', 'Creative', 'Tech', 'Academic'];
  }

  static List<TemplateModel> filterByCategory(String category) {
    if (category == 'All') return getTemplates();
    return getTemplates().where((t) => t.category == category).toList();
  }

  static List<TemplateModel> getPopularTemplates({int limit = 6}) {
    final List<TemplateModel> templates = List.from(getTemplates());
    templates.sort((a, b) => b.popularity.compareTo(a.popularity));
    return templates.take(limit).toList();
  }
